import type { InjectionKey } from "vue";
import { PGlite } from "@electric-sql/pglite";
import { live } from "@electric-sql/pglite/live";
import { provide } from "vue";

const PGLiteKey = Symbol("PGlite") as InjectionKey<PGlite>;

function provideDb() {
  const db = new PGlite("idb://advertising-db", {
    extensions: {
      live,
    },
  });

  provide(PGLiteKey, db);
  return db;
}

async function initDb(db: PGlite) {
  await db.exec(`
    CREATE TABLE IF NOT EXISTS clients (
      client_id INTEGER PRIMARY KEY,
      client_type VARCHAR(20) NOT NULL,
      client_name VARCHAR(50) NOT NULL,
      phone_number VARCHAR(20) NOT NULL,
      business_area VARCHAR(100) NOT NULL,
      client_address VARCHAR(50) NOT NULL
    );

    CREATE TABLE IF NOT EXISTS employees (
      employee_id INTEGER PRIMARY KEY,
      last_name VARCHAR(15) NOT NULL,
      first_name VARCHAR(15) NOT NULL,
      middle_name VARCHAR(15),
      position VARCHAR(50) NOT NULL,
      access_level VARCHAR(5) NOT NULL
    );

    CREATE TABLE IF NOT EXISTS campaigns (
      campaign_id INTEGER PRIMARY KEY,
      campaign_name VARCHAR(40) NOT NULL,
      start_date DATE NOT NULL,
      end_date DATE NOT NULL,
      budget DECIMAL(12,2) NOT NULL,
      goal VARCHAR(100) NOT NULL,
      status VARCHAR(40) NOT NULL,
      client_id INTEGER NOT NULL,
      views INTEGER NOT NULL,
      clicks INTEGER NOT NULL,
      sales INTEGER NOT NULL,
      FOREIGN KEY (client_id) REFERENCES clients(client_id)
    );

    CREATE TABLE IF NOT EXISTS target_audiences (
      audience_id INTEGER PRIMARY KEY,
      age_category VARCHAR(15) NOT NULL,
      gender VARCHAR(10) NOT NULL,
      region VARCHAR(40) NOT NULL,
      interests VARCHAR(100) NOT NULL,
      income_level VARCHAR(20) NOT NULL
    );

    CREATE TABLE IF NOT EXISTS campaigns_audiences (
      audience_id INTEGER NOT NULL,
      campaign_id INTEGER NOT NULL,
      PRIMARY KEY (audience_id, campaign_id),
      FOREIGN KEY (audience_id) REFERENCES target_audiences(audience_id),
      FOREIGN KEY (campaign_id) REFERENCES campaigns(campaign_id)
    );

    CREATE TABLE IF NOT EXISTS channels (
      channel_id INTEGER PRIMARY KEY,
      channel_name VARCHAR(40) NOT NULL,
      channel_type VARCHAR(30) NOT NULL,
      placement_cost DECIMAL(10,2) NOT NULL,
      audience_reach INTEGER NOT NULL
    );

    CREATE TABLE IF NOT EXISTS materials (
      material_id INTEGER PRIMARY KEY,
      material_name VARCHAR(50) NOT NULL,
      material_type VARCHAR(30) NOT NULL,
      creation_date DATE NOT NULL,
      campaign_id INTEGER NOT NULL,
      FOREIGN KEY (campaign_id) REFERENCES campaigns(campaign_id)
    );

    CREATE TABLE IF NOT EXISTS campaigns_channels (
      channel_id INTEGER NOT NULL,
      campaign_id INTEGER NOT NULL,
      PRIMARY KEY (channel_id, campaign_id),
      FOREIGN KEY (channel_id) REFERENCES channels(channel_id),
      FOREIGN KEY (campaign_id) REFERENCES campaigns(campaign_id)
    );

    CREATE TABLE IF NOT EXISTS campaigns_employees (
      employee_id INTEGER NOT NULL,
      campaign_id INTEGER NOT NULL,
      PRIMARY KEY (employee_id, campaign_id),
      FOREIGN KEY (employee_id) REFERENCES employees(employee_id),
      FOREIGN KEY (campaign_id) REFERENCES campaigns(campaign_id)
    );
  `);
}

